/// <summary>
/// Интерфейс объектов, с которыми игрок взаимодействует по клавише Е
/// (NPC, плакаты, двери и т. д.).
/// Реализуется любым компонентом, находящимся на объекте или его родителе.
/// </summary>
public interface IInteractable
{
    /// <summary>
    /// Подсказка для интерфейса, например "Поговорить". Может быть пустой.
    /// </summary>
    string InteractionPrompt { get; }

    /// <summary>
    /// Вызывается, когда игрок нажал клавишу взаимодействия, глядя на объект.
    /// </summary>
    void Interact();
}